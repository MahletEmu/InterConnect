/**
 * Smart matching function to map organizations to broad Ethiopian industry sectors.
 * Inspects company industry, about description, and internship fields.
 */
export function matchesCompanySector(
  company: {
    industry?: string;
    about?: string;
    internshipFields?: string[];
  },
  sector: string
): boolean {
  if (!sector || sector === 'All') return true;

  const ind = (company.industry || '').toLowerCase();
  const about = (company.about || '').toLowerCase();
  const fields = (company.internshipFields || []).map((f) => f.toLowerCase()).join(' ');

  switch (sector) {
    case 'Banking, Finance & Insurance':
      return (
        ind.includes('bank') ||
        ind.includes('financ') ||
        ind.includes('insur') ||
        ind.includes('payment') ||
        ind.includes('pos') ||
        ind.includes('fintech') ||
        fields.includes('banking') ||
        fields.includes('accounting & finance')
      );

    case 'Software, IT & Artificial Intelligence':
      return (
        ind.includes('software') ||
        ind.includes('artificial intelligence') ||
        ind.includes('robotics') ||
        ind.includes('cybersecurity') ||
        ind.includes('edtech') ||
        ind.includes('fintech') ||
        ind.includes('digital platform') ||
        ind.includes('digital transformation') ||
        ind.includes('pos payments') ||
        fields.includes('software engineering') ||
        fields.includes('computer science') ||
        fields.includes('artificial intelligence')
      );

    case 'Telecommunications & Network Infrastructure':
      return (
        ind.includes('telecom') ||
        ind.includes('ict') ||
        ind.includes('digital service') ||
        ind.includes('fiber') ||
        ind.includes('cloud infrastructure') ||
        ind.includes('cybersecurity')
      );

    case 'Healthcare, Hospitals & Pharmaceuticals':
      return (
        ind.includes('health') ||
        ind.includes('medic') ||
        ind.includes('hospital') ||
        ind.includes('pharm') ||
        ind.includes('clinic') ||
        ind.includes('surgery') ||
        ind.includes('dermatology') ||
        ind.includes('burn care') ||
        ind.includes('epidemiology') ||
        fields.includes('medicine') ||
        fields.includes('nursing') ||
        fields.includes('pharmacy')
      );

    case 'Civil Engineering, Construction & Architecture':
      // Avoid false positive on "reconstructive surgery"
      if (ind.includes('reconstructive')) return false;
      return (
        ind.includes('construction') ||
        ind.includes('civil') ||
        ind.includes('architecture') ||
        ind.includes('highways') ||
        ind.includes('bridges') ||
        ind.includes('building') ||
        ind.includes('prefab') ||
        ind.includes('water resource') ||
        ind.includes('hydraulics') ||
        fields.includes('civil engineering') ||
        fields.includes('architecture')
      );

    case 'Aviation, Energy, Logistics & Transport':
      return (
        ind.includes('aviation') ||
        ind.includes('energy') ||
        ind.includes('power') ||
        ind.includes('railway') ||
        ind.includes('shipping') ||
        ind.includes('logistics') ||
        ind.includes('dry port') ||
        ind.includes('transport') ||
        ind.includes('grid') ||
        ind.includes('hydropower') ||
        ind.includes('mobility')
      );

    case 'Manufacturing, FMCG & Industrial Materials':
      return (
        ind.includes('cement') ||
        ind.includes('manufactur') ||
        ind.includes('beverage') ||
        ind.includes('brewing') ||
        ind.includes('fmcg') ||
        ind.includes('chemical') ||
        ind.includes('paint') ||
        ind.includes('bottling')
      );

    case 'Agriculture, Agribusiness & Food Processing':
      return (
        ind.includes('agricultur') ||
        ind.includes('agronomy') ||
        ind.includes('sugar') ||
        ind.includes('coffee') ||
        ind.includes('commodity') ||
        ind.includes('plantation') ||
        ind.includes('biodiversity') ||
        fields.includes('agronomy') ||
        fields.includes('plant science')
      );

    case 'Law, Justice & Public Administration':
      return (
        ind.includes('law') ||
        ind.includes('justice') ||
        ind.includes('judiciary') ||
        ind.includes('human rights') ||
        ind.includes('investment') ||
        ind.includes('public administration') ||
        fields.includes('law')
      );

    case 'Media, Journalism & Communications':
      return (
        ind.includes('media') ||
        ind.includes('broadcast') ||
        ind.includes('journalism') ||
        ind.includes('press') ||
        ind.includes('editorial') ||
        ind.includes('publishing') ||
        ind.includes('radio') ||
        ind.includes('news') ||
        fields.includes('journalism') ||
        fields.includes('communications')
      );

    default:
      return ind.includes(sector.toLowerCase()) || about.includes(sector.toLowerCase());
  }
}

