/**
 * Filter verified companies according to student's department.
 * Smart matching handles synonyms, partial matching, and related fields.
 */
export function getCompaniesMatchingDepartment(dept?: string): Company[] {
  if (!dept || !dept.trim()) {
    return VERIFIED_ETHIOPIAN_COMPANIES;
  }
  const cleanDept = dept.toLowerCase().trim();

  const matched = VERIFIED_ETHIOPIAN_COMPANIES.filter((comp) => {
    if (!comp.internshipFields || comp.internshipFields.length === 0) return true;
    return comp.internshipFields.some((field) => {
      const cleanField = field.toLowerCase().trim();
      if (cleanField === cleanDept) return true;
      if (cleanField.includes(cleanDept) || cleanDept.includes(cleanField)) return true;

      // Smart semantic synonyms across Ethiopian fields
      if (cleanDept.includes('soft') && (cleanField.includes('soft') || cleanField.includes('comp') || cleanField.includes('info'))) return true;
      if (cleanDept.includes('comp') && (cleanField.includes('comp') || cleanField.includes('info') || cleanField.includes('soft'))) return true;
      if (cleanDept.includes('elect') && (cleanField.includes('elect') || cleanField.includes('power') || cleanField.includes('energy') || cleanField.includes('telecom'))) return true;
      if (cleanDept.includes('civil') && (cleanField.includes('civil') || cleanField.includes('construct') || cleanField.includes('arch') || cleanField.includes('water') || cleanField.includes('road'))) return true;
      if (cleanDept.includes('arch') && (cleanField.includes('arch') || cleanField.includes('civil') || cleanField.includes('construct') || cleanField.includes('interior'))) return true;
      if (cleanDept.includes('mech') && (cleanField.includes('mech') || cleanField.includes('industrial') || cleanField.includes('aeronaut') || cleanField.includes('automotive'))) return true;
      if (cleanDept.includes('water') && (cleanField.includes('water') || cleanField.includes('civil') || cleanField.includes('hydraulic') || cleanField.includes('environ'))) return true;
      if ((cleanDept.includes('med') || cleanDept.includes('health')) && (cleanField.includes('med') || cleanField.includes('health') || cleanField.includes('nurs') || cleanField.includes('pharm') || cleanField.includes('biomed'))) return true;
      if (cleanDept.includes('pharm') && (cleanField.includes('pharm') || cleanField.includes('health') || cleanField.includes('chem') || cleanField.includes('med'))) return true;
      if (cleanDept.includes('nurs') && (cleanField.includes('nurs') || cleanField.includes('health') || cleanField.includes('med'))) return true;
      if (cleanDept.includes('bio') && (cleanField.includes('bio') || cleanField.includes('health') || cleanField.includes('med') || cleanField.includes('agri'))) return true;
      if (cleanDept.includes('acc') && (cleanField.includes('acc') || cleanField.includes('fin') || cleanField.includes('bank') || cleanField.includes('audit'))) return true;
      if (cleanDept.includes('fin') && (cleanField.includes('fin') || cleanField.includes('acc') || cleanField.includes('econ') || cleanField.includes('bank') || cleanField.includes('insur'))) return true;
      if (cleanDept.includes('econ') && (cleanField.includes('econ') || cleanField.includes('fin') || cleanField.includes('acc') || cleanField.includes('bank') || cleanField.includes('invest'))) return true;
      if (cleanDept.includes('bus') && (cleanField.includes('bus') || cleanField.includes('manage') || cleanField.includes('market') || cleanField.includes('admin'))) return true;
      if (cleanDept.includes('manage') && (cleanField.includes('manage') || cleanField.includes('bus') || cleanField.includes('admin') || cleanField.includes('market'))) return true;
      if (cleanDept.includes('market') && (cleanField.includes('market') || cleanField.includes('bus') || cleanField.includes('comm') || cleanField.includes('media'))) return true;
      if (cleanDept.includes('law') && (cleanField.includes('law') || cleanField.includes('justic') || cleanField.includes('legal'))) return true;
      if (cleanDept.includes('agri') && (cleanField.includes('agri') || cleanField.includes('plant') || cleanField.includes('soil') || cleanField.includes('animal') || cleanField.includes('horti') || cleanField.includes('sugar'))) return true;
      if (cleanDept.includes('chem') && (cleanField.includes('chem') || cleanField.includes('paint') || cleanField.includes('cement') || cleanField.includes('material') || cleanField.includes('pharma'))) return true;
      if (cleanDept.includes('journ') && (cleanField.includes('journ') || cleanField.includes('comm') || cleanField.includes('media') || cleanField.includes('press') || cleanField.includes('broadcast'))) return true;
      if (cleanDept.includes('comm') && (cleanField.includes('comm') || cleanField.includes('journ') || cleanField.includes('media') || cleanField.includes('pr'))) return true;
      if (cleanDept.includes('data') && (cleanField.includes('data') || cleanField.includes('stat') || cleanField.includes('comp') || cleanField.includes('ai'))) return true;
      if (cleanDept.includes('ai') && (cleanField.includes('ai') || cleanField.includes('data') || cleanField.includes('comp') || cleanField.includes('robot'))) return true;
      if (cleanDept.includes('cyber') && (cleanField.includes('cyber') || cleanField.includes('comp') || cleanField.includes('info') || cleanField.includes('security'))) return true;
      if (cleanDept.includes('logist') && (cleanField.includes('logist') || cleanField.includes('supply') || cleanField.includes('transport') || cleanField.includes('rail'))) return true;

      return false;
    });
  });

  return matched.length > 0 ? matched : VERIFIED_ETHIOPIAN_COMPANIES;
}

